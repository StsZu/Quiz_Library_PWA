#!/usr/bin/env python3
"""Export the rules of Creator_quiz/tools/build_quiz.py for the browser validator (spec 002, T103).

Usage: python3 scripts/export_rules.py [--check]
Writes src/core/generated/build-quiz-rules.json: string presets and keys, wrapper keys, limits and the regular
expressions translated to JavaScript. Python \\b and \\w are Unicode-aware and JS ones are ASCII-only, so they are
rewritten with \\p{L}\\p{N}; every regex also ships samples with the Python result, which the unit tests replay
in JS. --check compares instead of writing (exit 1 when the file is stale). Creator_quiz is only read.
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "core" / "generated" / "build-quiz-rules.json"
WORD = r"[\p{L}\p{N}_]"

SAMPLES = {
    "lang": ["en", "pt-BR", "zh-Hant-TW", "uk", "e", "english", "en_US", "pl-"],
    "optionLabel": ["A. Paris", "  b) Paris", "C)  x", "Ab. x", "A.Paris", "А. кирилиця", "1. one"],
    "citation": ["Text [1]", "see [1, 2]", "range [1–3]", "[12-14]", "[a]", "[]", "array[0 ]", "arabic [١]"],
    "fence": ["```json\n{\"a\": 1}\n```", "```\n[]\n```", "```json \r\n{}\r\n```  ", "text ```json\n{}\n```", "```json\n{}"],
    "stringVar": ["Question {current} of {total}", "{n}: {text}", "{1bad} {ok_2}", "no vars"],
    "visual.uk": ["Що показано на схемі нижче?", "У ДІАГРАМІ видно", "пунктирна лінія", "Суцільною лінією", "вна схемі", "на схемічний", "в зображенні", "на сцені"],
    "visual.en": ["In the diagram above", "on the Figure", "in the diagrams", "a dashed line", "Dotted arrows", "within the chart", "solid lines"],
    "visual.pl": ["Na rysunku widać", "na schemacie", "linia przerywana", "linię ciągłą", "Zna rysunku", "na rysunkach", "w obrazku"],
}


def creator_dir():
    config = json.loads((ROOT / "content" / "courses.json").read_text(encoding="utf-8"))
    return (ROOT / config["source"]).resolve()


def to_js(regex):
    """Python pattern → {source, flags} for `new RegExp(source, flags)` with the same meaning on our inputs."""
    source = regex.pattern
    flags = "u"
    if regex.flags & re.I:
        flags += "i"
    if regex.flags & re.S:
        flags += "s"
    source = source.replace(r"\A", "^").replace(r"\Z", "$")
    source = source.replace(r"\w", WORD)
    source = source.replace(r"\d", r"\p{Nd}")  # Python \d is any Unicode decimal digit, JS \d only 0-9
    out, i = [], 0
    while i < len(source):
        if source.startswith(r"\b", i):
            leading = i == 0 or source[i - 1] == "|"
            # Leading \b before a letter = start or a non-word char before it (no lookbehind: Safari 16.0);
            # trailing \b after a letter = no word char after it.
            out.append(f"(?:^|[^{WORD[1:-1]}])" if leading else f"(?!{WORD})")
            i += 2
        else:
            out.append(source[i])
            i += 1
    source = "".join(out)
    if re.search(r"\\[bBAZ]", source):
        raise ValueError(f"untranslated escape in {regex.pattern!r}")
    return {"source": source, "flags": flags}


def sample(name, regex, texts):
    rows = []
    for text in texts:
        if name == "stringVar":
            rows.append({"text": text, "all": regex.findall(text)})
        elif name == "fence":
            m = regex.match(text.strip())
            rows.append({"text": text, "group": m.group(1) if m else None})
        elif name in ("lang", "optionLabel"):
            rows.append({"text": text, "match": regex.match(text) is not None})
        else:
            rows.append({"text": text, "match": regex.search(text) is not None})
    return rows


def build(bq, script):
    regexes = {
        "lang": bq.LANG_RE, "optionLabel": bq.OPTION_LABEL_RE, "citation": bq.CITATION_RE,
        "fence": bq.FENCE_RE, "stringVar": bq.STRING_VAR_RE,
    }
    regexes.update({f"visual.{lang}": rx for lang, rx in sorted(bq.VISUAL_REF_RE.items())})
    return {
        "_": "Generated by scripts/export_rules.py from Creator_quiz/tools/build_quiz.py. Do not edit.",
        "buildQuizSha256": hashlib.sha256(script.read_bytes()).hexdigest(),
        "questionKeys": list(bq.QUESTION_KEYS),
        "wrapperKeys": sorted(bq.WRAPPER_KEYS),
        "metaKeys": sorted(bq.META_KEYS),
        "rtlLangs": sorted(bq.RTL_LANGS),
        "invisibleChars": sorted(set(bq.INVISIBLE_RE.pattern.strip("[]"))),
        "limits": {
            "longestCorrectShare": bq.LONGEST_CORRECT_SHARE,
            "optionLengthRatio": bq.OPTION_LENGTH_RATIO,
            "optionLengthMin": bq.OPTION_LENGTH_MIN,
            "generationDefault": 10,
        },
        "stringKeys": {key: list(allowed) for key, allowed in bq.STRING_KEYS.items()},
        "presets": {lang: bq.PRESETS[lang] for lang in sorted(bq.PRESETS)},
        "regex": {name: to_js(rx) for name, rx in regexes.items()},
        "samples": {name: sample(name, regexes[name], texts) for name, texts in SAMPLES.items()},
    }


def main(argv=None):
    parser = argparse.ArgumentParser(prog="export_rules.py")
    parser.add_argument("--check", action="store_true", help="fail when the generated file is stale")
    args = parser.parse_args(argv)
    script = creator_dir() / "tools" / "build_quiz.py"
    if not script.is_file():
        print(f"error: Creator_quiz not found: {script}", file=sys.stderr)
        return 1
    sys.dont_write_bytecode = True  # Creator_quiz stays unchanged (constitution V.6)
    sys.path.insert(0, str(script.parent))
    import build_quiz  # noqa: E402

    if not build_quiz.INVISIBLE_RE.pattern.startswith("["):
        print("error: INVISIBLE_RE is no longer a character class; update export_rules.py", file=sys.stderr)
        return 1
    text = json.dumps(build(build_quiz, script), ensure_ascii=False, indent=1) + "\n"
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"error: {OUT.relative_to(ROOT)} is stale: run python3 scripts/export_rules.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
